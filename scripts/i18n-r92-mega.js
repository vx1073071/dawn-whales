// Sort keys by length (longest first for greedy matching)
const CMT_KEYS = Object.keys(CMT_MAP).sort((a, b) => b.length - a.length);

function translateCJK(text) {
  let result = text;
  for (const key of CMT_KEYS) {
    if (result.includes(key)) {
      result = result.split(key).join(CMT_MAP[key]);
    }
  }
  // For remaining CJK not in dictionary, keep as-is (will be counted later)
  return result;
}

function hasCJK(text) { return CJK.test(text); }

function processFile(filePath) {
  const c = fs.readFileSync(filePath, 'utf8');
  const lines = c.split('\n');
  let changes = 0;
  let inBlock = false;
  const newLines = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const trimmed = line.trim();

    // Block comment tracking
    if (trimmed.startsWith('/*')) {
      inBlock = true;
      if (hasCJK(line)) {
        newLines.push(translateCJK(line));
        changes++;
      } else {
        newLines.push(line);
      }
      if (trimmed.includes('*/')) inBlock = false;
      continue;
    }
    if (inBlock) {
      if (hasCJK(line)) {
        newLines.push(translateCJK(line));
        changes++;
      } else {
        newLines.push(line);
      }
      if (trimmed.includes('*/')) inBlock = false;
      continue;
    }
    // Single line comment (full line)
    if (trimmed.startsWith('//')) {
      if (hasCJK(line)) {
        newLines.push(translateCJK(line));
        changes++;
      } else {
        newLines.push(line);
      }
      continue;
    }
    // Inline comment: code // comment
    const inlineCommentIdx = line.search(/\/\/.*[\u4e00-\u9fff]/);
    if (inlineCommentIdx >= 0) {
      const codePart = line.substring(0, inlineCommentIdx);
      const commentPart = line.substring(inlineCommentIdx);
      newLines.push(codePart + translateCJK(commentPart));
      changes++;
      continue;
    }
    // No comment CJK - pass through
    newLines.push(line);
  }

  if (changes > 0) {
    fs.writeFileSync(filePath, newLines.join('\n'), 'utf8');
  }
  return changes;
}

// Walk directories
const dirs = ['src', 'electron'];
let totalChanges = 0;
let totalFiles = 0;

function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    const s = fs.statSync(p);
    if (s.isDirectory()) {
      if (!f.startsWith('.') && f !== 'node_modules' && f !== 'dist' && f !== 'locales' && f !== 'coverage') walk(p);
    } else if (/\.(ts|tsx|js|jsx)$/.test(f) && !f.includes('.test.') && !f.includes('.spec.')) {
      const c = processFile(p);
      if (c > 0) {
        totalChanges += c;
        totalFiles++;
        console.log(`  ${p.replace(/\\/g, '/')}: ${c} lines`);
      }
    }
  }
}

console.log('Processing comments...');
for (const dir of dirs) walk(dir);
console.log(`\nDone: ${totalChanges} comment lines translated in ${totalFiles} files`);
