def add_t_import(content):
    """Add useTranslation import and t() declaration if missing"""
    if "import { useTranslation }" in content:
        return content
    
    # Check if file has a React functional component
    if 'export default function' not in content and 'export function' not in content and 'export const' not in content:
        return content
    
    # Add import
    if 'from "react"' in content:
        content = content.replace('from "react"', 'from "react";\nimport { useTranslation } from "react-i18next"')
    elif "from 'react'" in content:
        content = content.replace("from 'react'", "from 'react';\nimport { useTranslation } from 'react-i18next'")
    else:
        first_import_line = content.find('import ')
        if first_import_line >= 0:
            # Find end of first import statement
            end_of_import = content.find('\n', first_import_line)
            indent = content[:first_import_line]
            content = content[:end_of_import+1] + f"\nimport {{ useTranslation }} from 'react-i18next';" + content[end_of_import+1:]
        else:
            content = "import { useTranslation } from 'react-i18next';\n" + content
    
    # Add const { t } = useTranslation() inside component functions
    # Find function/const component
    patterns = [
        r'(export default function\s+\w+\([^)]*\)\s*\{)',
        r'(export function\s+\w+\([^)]*\)\s*\{)',
    ]
    for p in patterns:
        match = re.search(p, content)
        if match:
            pos = match.end()
            content = content[:pos] + f"\n  const {{ t }} = useTranslation();" + content[pos:]
            break
    
    return content

def replace_hardcoded(text, filepath):
    """Replace hardcoded Chinese strings with t() calls"""
    origin = text
    count = 0
    
    for cn, key in sorted(I18N_MAP.items(), key=lambda x: -len(x[0])):  # Longest first
        if cn not in text:
            continue
        
        # JSX text: >中文<
        pattern1 = re.compile(r'>(' + re.escape(cn) + r')<')
        if pattern1.search(text):
            text = pattern1.sub(r'>{t("components.' + key + r'")}<', text)
            count += 1
        
        # JSX attribute: title="中文" → title={t('key')}
        pattern2 = re.compile(r'(title|placeholder|aria-label|label)="(' + re.escape(cn) + r')"')
        if pattern2.search(text):
            text = pattern2.sub(r'\1={t("components.' + key + r'")}', text)
            count += 1
            
        # String literal in TypeScript: '中文文本' or "中文文本"
        # Skip if already inside template literal or function call
        pattern3 = re.compile(r"(?<!t\()(?<!0.)(?<!\w)(?:'|\")(" + re.escape(cn) + r")(?:'|\")")
        if pattern3.search(text):
            text = pattern3.sub(r't("components.' + key + r'")', text)
            count += 1
    
    return text, count


files = glob.glob('src/components/trading/**/*.tsx', recursive=True)
total_replaced = 0
files_changed = 0

for f in sorted(files):
    with open(f, 'r', encoding='utf-8') as fh:
        original = fh.read()
    
    # Replace hardcoded strings
    content, reps = replace_hardcoded(original, f)
    
    if reps > 0:
        # Add useTranslation import if not present
        content = add_t_import(content)
        files_changed += 1
        total_replaced += reps
        print(f"  {f}: {reps} replacements")
        with open(f, 'w', encoding='utf-8') as fh:
            fh.write(content)

print(f"\nFiles changed: {files_changed}")
print(f"Total replacements: {total_replaced}")
