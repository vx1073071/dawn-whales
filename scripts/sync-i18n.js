// Read reference locale
const referencePath = path.join(LOCALES_DIR, REFERENCE_LOCALE);
const referenceData = JSON.parse(fs.readFileSync(referencePath, 'utf-8'));

console.log(`Reference locale: ${REFERENCE_LOCALE}`);
console.log(`Total namespaces: ${Object.keys(referenceData).length}`);

// Process each locale
for (const locale of LOCALES) {
  if (locale === 'zh-CN') continue; // Skip reference
  
  const localePath = path.join(LOCALES_DIR, `${locale}.json`);
  
  if (!fs.existsSync(localePath)) {
    console.log(`\n${locale}: File not found, creating from reference...`);
    fs.writeFileSync(localePath, JSON.stringify(referenceData, null, 2), 'utf-8');
    continue;
  }
  
  const localeData = JSON.parse(fs.readFileSync(localePath, 'utf-8'));
  let added = 0;
  
  // Check each namespace
  for (const [namespace, refKeys] of Object.entries(referenceData)) {
    if (!localeData[namespace]) {
      localeData[namespace] = {};
    }
    
    // Check each key
    for (const [key, refValue] of Object.entries(refKeys)) {
      if (localeData[namespace][key] === undefined) {
        // Try to use translation map
        const translations = TRANSLATIONS[locale] || {};
        if (translations[key]) {
          localeData[namespace][key] = translations[key];
        } else {
          // Use reference value as fallback
          localeData[namespace][key] = refValue;
        }
        added++;
      }
    }
  }
  
  // Write back
  fs.writeFileSync(localePath, JSON.stringify(localeData, null, 2), 'utf-8');
  
  if (added > 0) {
    console.log(`\n${locale}: Added ${added} missing keys`);
  } else {
    console.log(`\n${locale}: All keys present ✓`);
  }
}

console.log('\n✓ Sync complete!');
