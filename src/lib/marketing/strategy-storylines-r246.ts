/** Get stories for a specific strategy */
export function getStrategyStory(strategyId: string): StrategyStory | undefined {
  return STRATEGY_STORIES.find(s => s.strategyId === strategyId);
}

/** Generate the full story card for display */
export function generateStoryCard(strategyId: string): string {
  const s = getStrategyStory(strategyId);
  if (!s) return '';
  return `📖 ${s.strategyName} 背后的故事

🏛️ ${s.origin.title}
${s.origin.story}

⚔️ ${s.battle.title}
${s.battle.story}

💔 ${s.failure.title}
${s.failure.story}

📝 学会的三件事：
${s.lessons.map((l, i) => `  ${i + 1}. ${l}`).join('\n')}

[试用这个策略] [看更多故事]`;
}

