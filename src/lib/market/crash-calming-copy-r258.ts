// ═══════════════ 市场状态->崩盘级别映射 ═══════════════

export function getCrashLevel(dropPct: number): CrashLevel | undefined {
  // 从高到低匹配
  const sorted = [...CRASH_LEVELS].sort((a, b) => b.threshold - a.threshold);
  // 注意threshold是负值，所以取abs更大的
  for (const level of sorted) {
    if (dropPct <= level.threshold) return level;
  }
  return undefined; // 没跌到回调级别
}

export function getWhaleyCrashMessage(dropPct: number): string {
  const level = getCrashLevel(dropPct);
  if (!level) return WHALEY_CRASH_BRIEFING.messages[0].text;
  return WHALEY_CRASH_BRIEFING.messages.find(m => m.severity === level.id)?.text || WHALEY_CRASH_BRIEFING.messages[0].text;
}

export function getCrashHistorical(dropPct: number): string {
  const level = getCrashLevel(dropPct);
  return level?.historicalContext || '';
}

