export type BriefingScenario =
  | 'BULL_CONTINUATION'   // 延续涨势：昨天涨，盘前继续涨
  | 'BEAR_CONTINUATION'   // 延续跌势：昨天跌，盘前继续跌
  | 'REVERSAL_UP'          // 反转向上：昨天跌，盘前转涨
  | 'REVERSAL_DOWN'        // 反转向下：昨天涨，盘前转跌
  | 'GAP_UP'               // 跳空高开：盘前大幅高开
  | 'GAP_DOWN'             // 跳空低开：盘前大幅低开
  | 'FLAT_OPEN';           // 平开：盘前变化不大

export interface PreMarketBriefing {
  scenario: BriefingScenario;
  title: string;
  subtitle: string;
  overnight: string;       // 隔夜发生了什么
  premarket: string;       // 盘前在发生什么
  whatToExpect: string;    // 今天可以预期什么
  keyLevels: string;       // 关键位置在哪里
  strategyCheck: string;   // 你的策略应该怎么反应
  whaleBottomLine: string; // 鲸灵一句话总结
}

