export function getLesson(num: number): QuantLesson | undefined {
  return QUANT_30_LESSONS.find(l => l.num === num);
}

export function getLessonsByModule(module: string): QuantLesson[] {
  return QUANT_30_LESSONS.filter(l => l.module === module);
}

export function getLessonsByDifficulty(difficulty: Difficulty): QuantLesson[] {
  return QUANT_30_LESSONS.filter(l => l.difficulty === difficulty);
}

export function getModuleNames(): string[] {
  const names: string[] = [];
  for (const l of QUANT_30_LESSONS) {
    if (!names.includes(l.module)) names.push(l.module);
  }
  return names;
}

export function getProgressText(completed: number): string {
  const pct = ((completed / 30) * 100).toFixed(0);
  if (completed === 0) return '你还没有开始学习。30讲课程，从"量化是什么"到"建立实盘系统"。';
  if (completed < 6) return `完成了${completed}/30讲（${pct}%）——刚刚起步，坚持就是胜利！🐋`;
  if (completed < 15) return `完成了${completed}/30讲（${pct}%）——已经过半，你开始有模有样了！`;
  if (completed < 25) return `完成了${completed}/30讲（${pct}%）——马上快学完了，最后的模块是最实用的！`;
  if (completed < 30) return `完成了${completed}/30讲（${pct}%）——就差最后几讲了，加油！`;
  return '🏆 恭喜学完30讲！你已经从"量化是什么"走到了"我有自己的交易系统"。记住：真正的课程从今天开始。';
}

